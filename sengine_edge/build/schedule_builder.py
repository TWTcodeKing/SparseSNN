"""Build BA-MTTS execution schedule from EngineIR.

Adapts the EngineIR DAG (nodes + edges + bound classifications) into
the BoundAwareScheduler, runs the maximum-transition topological sort,
and returns the optimized node execution order.

The BA-MTTS schedule maximizes compute↔memory transitions between
consecutive kernel launches, enabling hardware-level overlap on the
same CUDA stream (tensor cores || load/store units).
"""

from __future__ import annotations

from sengine_edge.ir import BoundType, EngineIR
from sengine_edge.bound_aware_scheduler import (
    BoundAwareScheduler, Bound,
)
from sengine_edge.logger import logger


def build_schedule(ir: EngineIR) -> list[int]:
    """Build BA-MTTS execution order from EngineIR.

    Skips ZERO-cost nodes (Reshape, Flatten, Identity) — they are
    inserted back at their natural positions in the final schedule.

    Returns:
        Ordered list of ALL node IDs (including zero-cost), respecting
        dependencies and maximizing C↔M transitions for non-zero nodes.
    """
    sched = BoundAwareScheduler()

    # Map EngineIR node_id → scheduler op_id
    nid_to_oid: dict[int, int] = {}
    oid_to_nid: dict[int, int] = {}

    # Add non-zero nodes to scheduler
    for nid in ir.topo_order:
        node = ir.nodes[nid]
        if node.bound_type == BoundType.ZERO:
            continue

        bound = (Bound.COMPUTE if node.bound_type == BoundType.COMPUTE
                 else Bound.MEMORY)

        # Collect dependencies: predecessors that are also in the scheduler
        deps = []
        for pred_nid in ir.predecessors(nid):
            pred = ir.nodes.get(pred_nid)
            if pred is None:
                continue
            if pred.bound_type == BoundType.ZERO:
                # Look through zero-cost nodes to find real predecessors
                for pp_nid in ir.predecessors(pred_nid):
                    if pp_nid in nid_to_oid:
                        deps.append(nid_to_oid[pp_nid])
            elif pred_nid in nid_to_oid:
                deps.append(nid_to_oid[pred_nid])

        oid = sched.add(
            name=node.name,
            bound=bound,
            deps=deps,
            est_us=node.est_latency_us,
        )
        nid_to_oid[nid] = oid
        oid_to_nid[oid] = nid

    # Run BA-MTTS (maximize C↔M transitions for hardware overlap)
    # MOA (duration-aware) available via sched.schedule_moa() when latencies are profiled
    scheduled_oids = sched.schedule(verbose=False)
    transitions = sched.count_transitions(scheduled_oids)
    max_transitions = len(scheduled_oids) - 1 if len(scheduled_oids) > 1 else 0

    # Map back to EngineIR node IDs
    scheduled_nids = [oid_to_nid[oid] for oid in scheduled_oids]

    # Insert zero-cost nodes at their earliest valid position
    # (right before their first consumer in the schedule)
    zero_nodes = [nid for nid in ir.topo_order
                  if ir.nodes[nid].bound_type == BoundType.ZERO]

    full_schedule = _insert_zero_cost_nodes(scheduled_nids, zero_nodes, ir)

    logger.phase("SCHEDULE", "BA-MTTS: %d/%d transitions (%.0f%%), %d total ops",
                 transitions, max_transitions,
                 transitions / max_transitions * 100 if max_transitions > 0 else 0,
                 len(full_schedule))

    return full_schedule


def export_schedule_md(ir: EngineIR, schedule: list[int], path: str,
                       model_name: str = ""):
    """Export the BA-MTTS execution order to a Markdown file.

    Shows each kernel in execution order with bound type, C↔M transition
    markers, kernel variant, estimated latency, and summary statistics.

    Args:
        ir: Optimized EngineIR with bound types and kernel assignments.
        schedule: BA-MTTS execution order (list of node IDs).
        path: Output .md file path.
        model_name: Optional model name for the header.
    """
    lines = []
    lines.append(f"# Execution Order: {model_name or 'SNN Model'}")
    lines.append("")
    lines.append(f"Generated by sengine BA-MTTS scheduler.")
    lines.append(f"Total ops: {len(schedule)}")
    lines.append("")

    # Count transitions
    transitions = 0
    non_zero_count = 0
    prev_bound = None
    for nid in schedule:
        node = ir.nodes.get(nid)
        if node is None or node.bound_type == BoundType.ZERO:
            continue
        non_zero_count += 1
        if prev_bound is not None and node.bound_type != prev_bound:
            transitions += 1
        prev_bound = node.bound_type
    max_trans = non_zero_count - 1 if non_zero_count > 1 else 0
    pct = transitions / max_trans * 100 if max_trans > 0 else 0

    lines.append(f"## Summary")
    lines.append("")
    lines.append(f"| Metric | Value |")
    lines.append(f"|--------|-------|")
    lines.append(f"| Total ops | {len(schedule)} |")
    lines.append(f"| Compute (C) | {sum(1 for n in schedule if ir.nodes.get(n) and ir.nodes[n].bound_type == BoundType.COMPUTE)} |")
    lines.append(f"| Memory (M) | {sum(1 for n in schedule if ir.nodes.get(n) and ir.nodes[n].bound_type == BoundType.MEMORY)} |")
    lines.append(f"| Zero-cost (Z) | {sum(1 for n in schedule if ir.nodes.get(n) and ir.nodes[n].bound_type == BoundType.ZERO)} |")
    lines.append(f"| C↔M transitions | **{transitions}/{max_trans} ({pct:.0f}%)** |")
    total_us = sum(ir.nodes[n].est_latency_us for n in schedule
                   if ir.nodes.get(n) and ir.nodes[n].est_latency_us > 0)
    if total_us > 0:
        lines.append(f"| Estimated total | {total_us:.0f} us ({total_us/1000:.2f} ms) |")
    lines.append("")

    # Execution table
    lines.append(f"## Execution Order")
    lines.append("")
    lines.append(f"| # | Bound | Node | Kernel | Latency | Transition |")
    lines.append(f"|---|-------|------|--------|---------|------------|")

    prev_bound = None
    idx = 0
    for nid in schedule:
        node = ir.nodes.get(nid)
        if node is None:
            continue

        b = node.bound_type.value
        name = node.name[:45]
        kernel = node.assigned_kernel.name
        lat = f"{node.est_latency_us:.0f} us" if node.est_latency_us > 0 else "-"

        # Transition marker
        marker = ""
        if node.bound_type != BoundType.ZERO:
            if prev_bound is not None and node.bound_type != prev_bound:
                marker = "**C↔M**"
            prev_bound = node.bound_type

        lines.append(f"| {idx} | {b} | {name} | {kernel} | {lat} | {marker} |")
        idx += 1

    # Write file
    with open(path, 'w') as f:
        f.write('\n'.join(lines) + '\n')

    logger.phase("EXPORT", "Schedule exported to %s (%d ops, %d/%d transitions)",
                 path, len(schedule), transitions, max_trans)


def _insert_zero_cost_nodes(scheduled: list[int], zero_nodes: list[int],
                            ir: EngineIR) -> list[int]:
    """Insert zero-cost nodes into the BA-MTTS schedule.

    Each zero-cost node is placed right before its earliest consumer
    in the scheduled order, ensuring dependencies are satisfied.
    """
    if not zero_nodes:
        return scheduled

    # Build position map: nid → position in scheduled
    pos = {nid: i for i, nid in enumerate(scheduled)}

    # For each zero-cost node, find where to insert it
    insertions: list[tuple[int, int]] = []  # (position, nid)
    for znid in zero_nodes:
        # Find earliest consumer position
        succs = ir.successors(znid)
        earliest = len(scheduled)  # default: end
        for s in succs:
            if s in pos:
                earliest = min(earliest, pos[s])
        insertions.append((earliest, znid))

    # Sort by position (ascending), then insert from end to preserve indices
    insertions.sort(key=lambda x: x[0])

    result = list(scheduled)
    offset = 0
    for insert_pos, znid in insertions:
        result.insert(insert_pos + offset, znid)
        offset += 1

    return result
